/**
 * the two hooks that parse shell with unbash, each bundled into one self-contained file that is
 * committed: Claude Code copies a plugin into its cache without installing a pnpm lockfile's
 * dependencies, and loads a local marketplace's plugins in place. not minified, so the shipped file
 * stays readable. unbash is ISC-licensed, which requires its notice in every copy
 */
import { readFileSync } from "node:fs";
import { defineConfig } from "rolldown";

const unbashLicense = readFileSync("node_modules/unbash/LICENSE", "utf8");

const bundle = (input, file) => ({
  input,
  platform: "node",
  output: {
    file,
    format: "es",
    codeSplitting: false,
    banner: `// GENERATED by \`pnpm build\` from ${input}: edit that file, not this one`,
    postFooter: `/*! bundled: unbash (https://github.com/webpro-nl/unbash)\n${unbashLicense}*/`,
  },
});

export default defineConfig([
  bundle("plugins/hooks/src/no-bash.js", "plugins/hooks/hooks/no-bash.mjs"),
  bundle(
    "plugins/snip-hook/src/index.js",
    "plugins/snip-hook/dist/index.js",
  ),
]);
